"""All 22 TPC-H queries on warpstore vs DuckDB, on the same data (DuckDB's dbgen), with result checks.

  python bench/tpch_full.py [--sf 1] [--runs 3] [--keep DIR]

Starts its own warpstore server unless WARPSTORE_PORT points at one. The data is generated by
DuckDB's tpch extension, exported to Parquet and loaded into both systems from the same files;
the queries are the extension's (DuckDB dialect, which is also valid MySQL for these 22 except
where noted in DIALECT).
"""
import argparse, os, re, shutil, sys, tempfile, time
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests"))
import duckdb
from lib import Server, norm_rows, rows_close

ap = argparse.ArgumentParser()
ap.add_argument("--sf", type=float, default=1)
ap.add_argument("--runs", type=int, default=3)
ap.add_argument("--keep", help="directory for the Parquet files (reused when present)")
ap.add_argument("--only", help="comma-separated query numbers")
args = ap.parse_args()

work = args.keep or tempfile.mkdtemp(prefix="tpch-")
os.makedirs(work, exist_ok=True)
d = duckdb.connect()
d.execute("INSTALL tpch; LOAD tpch")
tables = ["region", "nation", "supplier", "customer", "part", "partsupp", "orders", "lineitem"]
if not all(os.path.exists(os.path.join(work, f"{t}.parquet")) for t in tables):
    t0 = time.time()
    d.execute(f"CALL dbgen(sf={args.sf})")
    for t in tables:
        d.execute(f"COPY {t} TO '{work}/{t}.parquet' (FORMAT parquet)")
    print(f"generated SF{args.sf} in {time.time() - t0:.1f}s -> {work}")
    d.close()
    d = duckdb.connect()
    d.execute("LOAD tpch")
for t in tables:
    d.execute(f"CREATE OR REPLACE TABLE {t} AS SELECT * FROM '{work}/{t}.parquet'")
d.execute("SET default_null_order = 'nulls_first_on_asc_last_on_desc'")


def mysql_type(t):
    t = t.upper()
    if t.startswith("DECIMAL"):
        return t
    return {"INTEGER": "INT", "BIGINT": "BIGINT", "DATE": "DATE", "DOUBLE": "DOUBLE"}.get(t, "VARCHAR(200)")


KEYS = {"region": "PRIMARY KEY (r_regionkey)", "nation": "PRIMARY KEY (n_nationkey)", "supplier": "PRIMARY KEY (s_suppkey)",
        "customer": "PRIMARY KEY (c_custkey)", "part": "PRIMARY KEY (p_partkey)", "partsupp": "SHARD KEY (ps_partkey)",
        "orders": "PRIMARY KEY (o_orderkey), SORT KEY (o_orderdate)", "lineitem": "SHARD KEY (l_orderkey), SORT KEY (l_shipdate)"}

srv = None
if os.environ.get("WARPSTORE_PORT"):
    srv = Server(data_dir=None, http=False)
    srv.port = int(os.environ["WARPSTORE_PORT"])
else:
    srv = Server(name="tpch", http=False).start()
cur = srv.cursor()
cur.execute("CREATE DATABASE IF NOT EXISTS tpch")
cur.execute("USE tpch")
cur.execute("SHOW TABLES")
have = {r[0] for r in cur.fetchall()}
for t in tables:
    if t in have:
        continue
    cols = d.execute(f"DESCRIBE {t}").fetchall()
    ddl = ", ".join(f"{c[0]} {mysql_type(c[1])}" for c in cols)
    cur.execute(f"CREATE TABLE {t} ({ddl}, {KEYS[t]})")
    t0 = time.time()
    cur.execute(f"LOAD DATA INFILE '{work}/{t}.parquet' INTO TABLE {t}")
    print(f"loaded {t} in {time.time() - t0:.2f}s")
cur.execute("OPTIMIZE TABLE lineitem")
cur.fetchall()

queries = dict(d.execute("SELECT query_nr, query FROM tpch_queries()").fetchall())
only = {int(x) for x in args.only.split(",")} if args.only else None


def timed(fn):
    best, out, first = None, None, None
    for _ in range(args.runs):
        t0 = time.perf_counter()
        out = fn()
        dt = time.perf_counter() - t0
        first = dt if first is None else first
        best = dt if best is None else min(best, dt)
    timed.first = first
    return best, out


def ws(q):
    cur.execute(q)
    return cur.fetchall()


rows = []
fails = 0
for n in sorted(queries):
    if only and n not in only:
        continue
    q = queries[n].strip().rstrip(";")
    dt_d, want = timed(lambda: d.execute(q).fetchall())
    ordered = re.search(r"order\s+by", q, re.I) is not None
    first_d = timed.first
    try:
        dt_w, got = timed(lambda: ws(q))
        first_w = timed.first
    except Exception as e:
        rows.append((n, None, dt_d, None, None, f"ERROR {str(e)[:150]}"))
        fails += 1
        continue
    a, b = norm_rows(got, ordered=ordered, places=2), norm_rows(want, ordered=ordered, places=2)
    ok = a == b or rows_close(a, b, 1e-6, 1e-2)
    if not ok:
        fails += 1
    rows.append((n, dt_w, dt_d, first_w, first_d, "ok" if ok else f"MISMATCH {len(a)} vs {len(b)} rows: {[(x, y) for x, y in zip(a, b) if x != y][:1]}"))

print(f"\nTPC-H SF{args.sf}, best of {args.runs} and first run (seconds)")
print(f"{'Q':>3} {'warpstore':>10} {'duckdb':>8} {'speedup':>8} {'ws first':>9} {'dk first':>9}  result")
geo = [0.0] * 4
k = 0
import math
for n, w, dd, fw, fd, res in rows:
    sp = f"{dd / w:.1f}x" if w else "-"
    print(f"{n:>3} {w if w is None else round(w, 4):>10} {dd:>8.4f} {sp:>8} {fw if fw is None else round(fw, 4):>9} {fd if fd is None else round(fd, 4):>9}  {res}")
    if w:
        for i, v in enumerate((w, dd, fw, fd)):
            geo[i] += math.log(v)
        k += 1
if k:
    g = [math.exp(x / k) * 1000 for x in geo]
    print(f"geomean hot: warpstore {g[0]:.1f} ms, duckdb {g[1]:.1f} ms; first run: warpstore {g[2]:.1f} ms, duckdb {g[3]:.1f} ms ({k} queries)")
print(f"{fails} failing")
if not os.environ.get("WARPSTORE_PORT"):
    srv.stop()
if not args.keep:
    shutil.rmtree(work, ignore_errors=True)
