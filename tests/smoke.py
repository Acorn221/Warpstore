import pymysql, sys
port = int(sys.argv[1]) if len(sys.argv) > 1 else 3307
c = pymysql.connect(host="127.0.0.1", port=port, user="root", password="x", autocommit=True)
cur = c.cursor()
def q(sql):
    cur.execute(sql)
    rows = cur.fetchall()
    print(sql, "->", rows)
    return rows
